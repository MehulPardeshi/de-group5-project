-- Store the original NOAA Storm Events details CSVs without changing the data.
-- Every column is TEXT and there are no constraints, so no row can be dropped.
CREATE TABLE IF NOT EXISTS raw.storm_events_details (
    begin_yearmonth TEXT,
    begin_day TEXT,
    begin_time TEXT,
    end_yearmonth TEXT,
    end_day TEXT,
    end_time TEXT,
    episode_id TEXT,
    event_id TEXT,
    state TEXT,
    state_fips TEXT,
    year TEXT,
    month_name TEXT,
    event_type TEXT,
    cz_type TEXT,
    cz_fips TEXT,
    cz_name TEXT,
    wfo TEXT,
    begin_date_time TEXT,
    cz_timezone TEXT,
    end_date_time TEXT,
    injuries_direct TEXT,
    injuries_indirect TEXT,
    deaths_direct TEXT,
    deaths_indirect TEXT,
    damage_property TEXT,
    damage_crops TEXT,
    source TEXT,
    magnitude TEXT,
    magnitude_type TEXT,
    flood_cause TEXT,
    category TEXT,
    tor_f_scale TEXT,
    tor_length TEXT,
    tor_width TEXT,
    tor_other_wfo TEXT,
    tor_other_cz_state TEXT,
    tor_other_cz_fips TEXT,
    tor_other_cz_name TEXT,
    begin_range TEXT,
    begin_azimuth TEXT,
    begin_location TEXT,
    end_range TEXT,
    end_azimuth TEXT,
    end_location TEXT,
    begin_lat TEXT,
    begin_lon TEXT,
    end_lat TEXT,
    end_lon TEXT,
    episode_narrative TEXT,
    event_narrative TEXT,
    data_source TEXT
);
